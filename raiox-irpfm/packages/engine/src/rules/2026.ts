function incomeType(
  definition: Omit<
    IncomeTypeDefinition,
    "requiresMonth" | "requiresPayer" | "investable" | "estimatedTaxRate"
  > &
    Partial<
      Pick<
        IncomeTypeDefinition,
        "requiresMonth" | "requiresPayer" | "investable" | "estimatedTaxRate"
      >
    >,
): IncomeTypeDefinition {
  return {
    requiresMonth: false,
    requiresPayer: false,
    investable: false,
    estimatedTaxRate: null,
    ...definition,
  };
}

